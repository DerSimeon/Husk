        buf.buf.writeFloat(fovModifier)
    }
}

/**
 * Adds one listed player to the tab list. 1.19.3+ (Player Info Update) writes the
 * add_player | update_game_mode | update_listed | update_latency actions for a single entry;
 * 1.8–1.19.2 used the old action-enum Player Info with a single add_player action.
 */
class PlayerInfoAddPacket(
    val uuid: UUID,
    val name: String,
    val gamemode: Int,
    val latency: Int = 0,
) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        if (!version.isAtLeast(Version.MINECRAFT_1_19_3)) return encodeLegacy(buf, version)
        buf.buf.writeByte(ACTIONS)
        buf.writeVarInt(1) // one entry
        buf.writeUUID(uuid)
        // add_player: profile name + (empty) properties
        buf.writeString(name)
        buf.writeVarInt(0)
        buf.writeVarInt(gamemode) // update_game_mode
        buf.writeBoolean(true) // update_listed
        buf.writeVarInt(latency) // update_latency
    }

    private fun encodeLegacy(buf: ByteMessage, version: Version) {
        buf.writeVarInt(0) // action: add_player
        buf.writeVarInt(1) // one entry
        buf.writeUUID(uuid)
        buf.writeString(name)
        buf.writeVarInt(0) // properties
        buf.writeVarInt(gamemode)
        buf.writeVarInt(latency)
        buf.writeBoolean(false) // no display name
        if (version.isAtLeast(Version.MINECRAFT_1_19)) buf.writeBoolean(false) // no chat-signing key
    }

    private companion object {
        // add_player(0x01) | update_game_mode(0x04) | update_listed(0x08) | update_latency(0x10)
        const val ACTIONS = 0x1D
    }
}

class PluginMessagePacket(val channel: NamespacedKey, val data: ByteArray) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        // Channel is a NamespacedKey (identifier) since 1.13; a plain string before (TODO).
        buf.writeNamespacedKey(channel)
        buf.buf.writeBytes(data)
    }
}

