/** Boss Bar (1.9+). Colours/divisions are wire enum ordinals; map from Adventure's enums when sending. */
class BossBarPacket(val uuid: UUID, val action: Action) : ClientboundPacket {
    sealed interface Action {
        val id: Int
        fun encode(buf: ByteMessage, version: Version)
    }

    class Add(
        val title: Component,
        val health: Float,
        val color: Int,
        val division: Int,
        val flags: Int,
    ) : Action {
        override val id = 0
        override fun encode(buf: ByteMessage, version: Version) {
            buf.writeComponent(title, version)
            buf.buf.writeFloat(health)
            buf.writeVarInt(color)
            buf.writeVarInt(division)
            buf.buf.writeByte(flags)
        }
    }

    object Remove : Action {
        override val id = 1
        override fun encode(buf: ByteMessage, version: Version) = Unit
    }

    class UpdateHealth(val health: Float) : Action {
        override val id = 2
        override fun encode(buf: ByteMessage, version: Version) = buf.buf.writeFloat(health).let {}
    }

    class UpdateTitle(val title: Component) : Action {
        override val id = 3
        override fun encode(buf: ByteMessage, version: Version) = buf.writeComponent(title, version)
    }

    override fun encode(buf: ByteMessage, version: Version) {
        buf.writeUUID(uuid)
        buf.writeVarInt(action.id)
        action.encode(buf, version)
    }
}

/**
 * Synchronize Player Position. 1.21.2+ rewrote this: teleport id first, then position, a
 * delta-movement vector, rotation, and a u32 relatives bitfield. 1.9–1.21.1 used the older
 * position/rotation/byte-flags/teleport-id shape; 1.8 has no teleport id, and 1.17–1.19.3 append
 * a "dismount vehicle" boolean.
 */
class PlayerPositionPacket(
    val x: Double,
    val y: Double,
    val z: Double,
    val yaw: Float,
    val pitch: Float,
    val flags: Int,
    val teleportId: Int,
) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        if (version.isAtLeast(Version.MINECRAFT_1_21_2)) {
            buf.writeVarInt(teleportId)
            buf.buf.writeDouble(x); buf.buf.writeDouble(y); buf.buf.writeDouble(z)
            buf.buf.writeDouble(0.0); buf.buf.writeDouble(0.0); buf.buf.writeDouble(0.0) // delta movement
            buf.buf.writeFloat(yaw); buf.buf.writeFloat(pitch)
            buf.buf.writeInt(flags) // u32 relatives bitfield
        } else {
            buf.buf.writeDouble(x)
            buf.buf.writeDouble(y)
            buf.buf.writeDouble(z)
            buf.buf.writeFloat(yaw)
            buf.buf.writeFloat(pitch)
            buf.buf.writeByte(flags)
            if (version.isAtLeast(Version.MINECRAFT_1_9)) buf.writeVarInt(teleportId)
            if (version.isAtLeast(Version.MINECRAFT_1_17) && !version.isAtLeast(Version.MINECRAFT_1_19_4)) {
                buf.writeBoolean(false) // dismount vehicle
            }
        }
    }
}

/** Player Abilities (clientbound): flags bitfield + fly speed + fov modifier. */
class PlayerAbilitiesPacket(val flags: Int, val flyingSpeed: Float, val fovModifier: Float) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        buf.buf.writeByte(flags)
