/**
 * Join Game / Login (play). Three eras:
 *  - 1.8–1.15: numeric dimension (-1/0/1), no registries.
 *  - 1.16–1.20.1: the whole registry [codec] is embedded here (1.16.2–1.18.2 also embed the
 *    dimension type's element; 1.16 and 1.19+ name it instead).
 *  - 1.20.2+: registries went to CONFIGURATION; the dimension type is named (1.20.2–1.20.4) or
 *    indexed by [dimensionId] (1.20.5+).
 * [dimensionName] is the dimension_type key (also used as the world name). [codec] is the captured
 * registry codec for the client's protocol; required only for 1.16–1.20.1.
 */
class JoinGamePacket(
    val entityId: Int,
    val dimensionId: Int,
    val dimensionName: String,
    val gamemode: Int,
    val viewDistance: Int = 10,
    val codec: CompoundBinaryTag? = null,
) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) = encode(buf, version, version.protocol)

    override fun encode(buf: ByteMessage, version: Version, protocol: Int) = when {
        version.isAtLeast(Version.MINECRAFT_1_20_2) -> encodeConfigured(buf, version)
        version.isAtLeast(Version.MINECRAFT_1_16) -> encodeWithCodec(buf, version)
        else -> encodeLegacy(buf, version, protocol)
    }

    private fun encodeLegacy(buf: ByteMessage, version: Version, protocol: Int) {
        buf.buf.writeInt(entityId)
        buf.buf.writeByte(gamemode)
        val dimension = when (dimensionName) {
            "minecraft:the_nether" -> -1
            "minecraft:the_end" -> 1
            else -> 0
        }
        // Dimension widened from i8 to i32 in 1.9.1 (protocol 108) — finer than the Version enum.
        if (protocol >= PROTOCOL_1_9_1) buf.buf.writeInt(dimension) else buf.buf.writeByte(dimension)
        if (!version.isAtLeast(Version.MINECRAFT_1_14)) buf.buf.writeByte(0) // difficulty: peaceful
        if (version.isAtLeast(Version.MINECRAFT_1_15)) buf.buf.writeLong(0L) // hashed seed
        buf.buf.writeByte(MAX_PLAYERS)
        buf.writeString("default") // level type
        if (version.isAtLeast(Version.MINECRAFT_1_14)) buf.writeVarInt(viewDistance)
        buf.writeBoolean(false) // reduced debug info
        if (version.isAtLeast(Version.MINECRAFT_1_15)) buf.writeBoolean(true) // enable respawn screen
    }

    private fun encodeWithCodec(buf: ByteMessage, version: Version) {
        val codec = requireNotNull(codec) { "JoinGamePacket needs the registry codec on $version" }
        buf.buf.writeInt(entityId)
        if (version.isAtLeast(Version.MINECRAFT_1_16_2)) buf.writeBoolean(false) // isHardcore
        buf.buf.writeByte(gamemode)
        buf.buf.writeByte(0xFF) // previous gamemode = -1 (none)
        buf.writeList(listOf(dimensionName)) { buf.writeString(it) } // world names
        buf.writeCompoundTag(codec, version)
        if (version.isAtLeast(Version.MINECRAFT_1_16_2) && !version.isAtLeast(Version.MINECRAFT_1_19)) {
            buf.writeCompoundTag(dimensionElement(codec), version) // 1.16.2–1.18.2: the type itself
        } else {
            buf.writeString(dimensionName) // 1.16–1.16.1 and 1.19+: the type's key
        }
        buf.writeString(dimensionName) // world name
        buf.buf.writeLong(0L) // hashed seed
        if (version.isAtLeast(Version.MINECRAFT_1_16_2)) buf.writeVarInt(MAX_PLAYERS) else buf.buf.writeByte(MAX_PLAYERS)
        buf.writeVarInt(viewDistance)
        if (version.isAtLeast(Version.MINECRAFT_1_18)) buf.writeVarInt(viewDistance) // simulation distance
        buf.writeBoolean(false) // reduced debug info
        buf.writeBoolean(true) // enable respawn screen
        buf.writeBoolean(false) // is debug
        buf.writeBoolean(false) // is flat
        if (version.isAtLeast(Version.MINECRAFT_1_19)) buf.writeBoolean(false) // no death location
        if (version.isAtLeast(Version.MINECRAFT_1_20)) buf.writeVarInt(0) // portal cooldown
    }

    private fun encodeConfigured(buf: ByteMessage, version: Version) {
        buf.buf.writeInt(entityId)
        buf.writeBoolean(false) // isHardcore
        buf.writeList(listOf(dimensionName)) { buf.writeString(it) } // world names
        buf.writeVarInt(MAX_PLAYERS) // max players (client ignores)
        buf.writeVarInt(viewDistance)
        buf.writeVarInt(viewDistance) // simulation distance
        buf.writeBoolean(false) // reduced debug info
        buf.writeBoolean(true) // enable respawn screen
        buf.writeBoolean(false) // do limited crafting
        // SpawnInfo
        if (version.isAtLeast(Version.MINECRAFT_1_20_5)) buf.writeVarInt(dimensionId) else buf.writeString(dimensionName)
        buf.writeString(dimensionName)
        buf.buf.writeLong(0L) // hashed seed
        if (version.isAtLeast(Version.MINECRAFT_26_3)) {
            buf.writeVarInt(gamemode)
            buf.writeVarInt(0) // previous gamemode: optional VarInt, 0 = none (else id + 1)
        } else {
            buf.buf.writeByte(gamemode) // gamemode (i8)
            buf.buf.writeByte(0xFF) // previous gamemode = -1 (none)
        }
        buf.writeBoolean(false) // is debug
        buf.writeBoolean(false) // is flat
        buf.writeBoolean(false) // no death location
        buf.writeVarInt(0) // portal cooldown
        if (version.isAtLeast(Version.MINECRAFT_1_21_2)) buf.writeVarInt(63) // sea level (1.21.2+)
        if (version.isAtLeast(Version.MINECRAFT_26_2)) buf.writeBoolean(false) // online mode (26.2+); offline
        if (version.isAtLeast(Version.MINECRAFT_1_20_5)) buf.writeBoolean(false) // enforces secure chat
    }

    /** The dimension_type registry element for [dimensionName] (first entry if it isn't listed). */
    private fun dimensionElement(codec: CompoundBinaryTag): CompoundBinaryTag {
        val entries = codec.getCompound("minecraft:dimension_type").getList("value", BinaryTagTypes.COMPOUND)
            .map { it as CompoundBinaryTag }
        val entry = entries.firstOrNull { it.getString("name") == dimensionName } ?: entries.first()
        return entry.getCompound("element")
    }

    private companion object {
        const val MAX_PLAYERS = 20
        const val PROTOCOL_1_9_1 = 108
    }
}

/** Game Event (game_state_change): a u8 reason + f32 value. Reason 13 = start waiting for chunks. */
class GameEventPacket(val reason: Int, val value: Float = 0f) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        buf.buf.writeByte(reason)
        buf.buf.writeFloat(value)
    }
}

/** Set Center Chunk (update_view_position): the chunk the client centers its view on. */
class SetCenterChunkPacket(val chunkX: Int, val chunkZ: Int) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        buf.writeVarInt(chunkX)
        buf.writeVarInt(chunkZ)
    }
}

/**
 * An all-air Chunk Data + light packet (map_chunk). Every section is a single-valued air palette
 * with the given [biomeId]; [sectionCount] must equal the dimension height / 16. Empty heightmaps,
 * block entities, and light — enough for a void limbo. Only sent to 1.20.3+ (older clients leave
 * the terrain screen without chunks). Layout by version:
 *  - 1.20.3–1.21.4: NBT heightmaps; paletted containers carry a (zero) data-array length.
 *  - 1.21.5+: heightmaps are a prefixed array; the data-array length is gone.
 *  - 26.1+: each section adds a fluid count after the block count.
 */
class EmptyChunkPacket(
    val chunkX: Int,
    val chunkZ: Int,
    val sectionCount: Int,
    val biomeId: Int,
) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        buf.buf.writeInt(chunkX)
        buf.buf.writeInt(chunkZ)
        val compact = version.isAtLeast(Version.MINECRAFT_1_21_5) // array heightmaps, no data-array lengths
        if (compact) buf.writeVarInt(0) else buf.writeCompoundTag(CompoundBinaryTag.empty(), version)

        val sections = Unpooled.buffer()
        try {
            val out = ByteMessage(sections)
            // Single-valued paletted container: bits per entry 0, the value, then (pre-1.21.5) an empty data array.
            fun singleValued(value: Int) {
                sections.writeByte(0)
                out.writeVarInt(value)
                if (!compact) out.writeVarInt(0)
            }
            repeat(sectionCount) {
                sections.writeShort(0) // block count
                if (version.isAtLeast(Version.MINECRAFT_26_1)) sections.writeShort(0) // fluid count
                singleValued(0) // block states: air
                singleValued(biomeId) // biomes
            }
            buf.writeVarInt(sections.readableBytes())
            buf.buf.writeBytes(sections)
        } finally {
            sections.release()
        }

        buf.writeVarInt(0) // block entities
        buf.writeVarInt(0) // sky light mask
        buf.writeVarInt(0) // block light mask
        buf.writeVarInt(0) // empty sky light mask
        buf.writeVarInt(0) // empty block light mask
        buf.writeVarInt(0) // sky light arrays
        buf.writeVarInt(0) // block light arrays
    }
}

class KeepAlivePacket(val id: Long) : ClientboundPacket {
    override fun encode(buf: ByteMessage, version: Version) {
        // Keep Alive payload became a Long in 1.12.2 (protocol 340); VarInt in 1.12.1 and before.
        if (version.isAtLeast(Version.MINECRAFT_1_12_2)) buf.buf.writeLong(id) else buf.writeVarInt(id.toInt())
    }
}

